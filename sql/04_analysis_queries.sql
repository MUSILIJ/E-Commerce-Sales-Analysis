# 8. Which customers placed more than one order?

SELECT
    customers.customer_name,
    COUNT(orders.order_id) AS number_of_orders
FROM customers
JOIN orders
    ON customers.customer_id = orders.customer_id
GROUP BY
    customers.customer_id,
    customers.customer_name
HAVING
    COUNT(orders.order_id) > 1
ORDER BY
    number_of_orders DESC;


# 9. What is the average order value?

SELECT
    AVG(order_totals.order_total) AS average_order_value
FROM
(
    SELECT
        orders.order_id,
        SUM(order_items.quantity * order_items.price) AS order_total
    FROM orders
    JOIN order_items
        ON orders.order_id = order_items.order_id
    GROUP BY
        orders.order_id
) AS order_totals;


# 10. Which customers have not placed any orders?

SELECT
    customers.customer_name,
    customers.city
FROM customers
LEFT JOIN orders
    ON customers.customer_id = orders.customer_id
WHERE
    orders.order_id IS NULL;


