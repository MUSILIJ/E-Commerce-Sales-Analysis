# 17. Which category has the highest average product price?

SELECT
    products.category,
    ROUND(AVG(products.price), 2) AS average_price
FROM products
GROUP BY
    products.category
ORDER BY
    average_price DESC;


# 18. What is the average number of units purchased per order?

SELECT
    ROUND(AVG(order_quantities.total_units), 2) AS average_units_per_order
FROM
(
    SELECT
        orders.order_id,
        SUM(order_items.quantity) AS total_units
    FROM orders
    JOIN order_items
        ON orders.order_id = order_items.order_id
    GROUP BY
        orders.order_id
) AS order_quantities;


# 19. What are the top 5 highest-value orders?

