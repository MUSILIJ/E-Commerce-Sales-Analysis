# 14. What percentage of total revenue was generated by each product?

SELECT
    products.product_name,
    SUM(order_items.quantity * order_items.price) AS product_revenue,
    ROUND(
        SUM(order_items.quantity * order_items.price)
        /
        (SELECT SUM(quantity * price) FROM order_items)
        * 100,
        2
    ) AS revenue_percentage
FROM products
JOIN order_items
    ON products.product_id = order_items.product_id
GROUP BY
    products.product_id,
    products.product_name
ORDER BY
    revenue_percentage DESC;


